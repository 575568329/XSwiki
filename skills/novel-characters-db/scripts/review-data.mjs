// 世代标签归一: 各种写法 -> 字辈字符
export function normGeneration(g) {
  if (!g) return '';
  const order = ['木', '长', '项', '通', '玄', '渊', '曦', '周', '绛', '遂', '阙'];
  for (const z of order) if (g.includes(z)) return z;
  return g; // 无法归一的保留原文
}

export function normFaction(f) {
  if (!f) return '';
  if (f.includes('李家') || f.includes('李氏')) return '李家';
  return f;
}
