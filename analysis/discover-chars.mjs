const TAIL_JUNK = /(随口|随后|忍不住|微微|轻轻|轻声|沉声|低声|大声|慢慢|缓缓|淡淡|笑着|忽然|突然|一边|同时|连忙|急忙|当即|立刻|渐渐|默默|悄悄|偷偷|静静|深深|匆匆|似笑非笑|不动声色|若无其事|不由得|有些|苦笑|冷笑|摇头|点头|咧嘴|耸肩|摊手|一怔|一愣|抬头|回头|转身|起身|笑|闻言|听罢|见状|说着|开口|接着|顿时|随即|立马|半晌|良久|一眼|几声|一声|两声)+$/;
const TAIL_CHAR = /[了点起过出上来去到说要会能可就都也又还再才只更最很太好大小多少地着之的摇皱抬低站坐走停留冲奔看听想讲谈问答喊叫唤骂打挥掷投推拉抱递接叹微是]/;
const PREFIX_JUNK = /^(见到|看到|望见|听见|听到|看着|望着|对着|对|向|与|和|同|跟|让|使|被|把|给|是|也|都|才|就|又|还|便|即|却|而|在|从|由|当|待|等|令|叫|请|帮|陪|扶|拉|扯|拖|携|领|带|随|使|见到萧炎|直到|至少|至此|于是|此时|此刻|随后|接着|旋即|当下|方才|刚刚|刚才|顿时|瞬间|立刻|马上|立即|随即|当即|死死|一道道|一道|一名|那名|这名|每个|某个|任何|哪些|这么|那么|只见|但见|只听|只觉|不紧不慢|若有所思|下意识|好奇|一愣|一怔|见到|见到他)+/;
const normalize = name => {
  let n = name.replace(/^[“”"'\s]+/, '');
  for (;;) {
    const before = n;
    n = n.replace(PREFIX_JUNK, '');
    n = n.replace(TAIL_JUNK, '');
    if (n.length >= 3 && TAIL_CHAR.test(n[n.length - 1])) n = n.slice(0, -1);
    if (n === before) break;
  }
  return n;
};
const cand = new Map();
const add = (name, verb) => {
  const n = normalize(name);
  if (!n || n.length < 2 || n.length > 6) return;
  if (/[的了吗呢吧啊呀哦嘛]|们$|之说|他们|我们|她们|它们/.test(n)) return;
  if (STOP.has(n)) return;
  const e = cand.get(n) || { speaker: 0, verbs: new Set() };
  e.speaker++;
  e.verbs.add(verb);
  cand.set(n, e);
};
for (const f of files) {
  const t = fs.readFileSync(path.join(CH_DIR, f), 'utf8');
  for (const v of VERBS) {
    const re = new RegExp('(?<![\\u4e00-\\u9fa5·])(' + (LIMING ? '[\\u4e00-\\u9fa5·]{2,6}' : '[\\u4e00-\\u9fa5]{2,4}') + ')' + v, 'g');
    let m;
    while ((m = re.exec(t))) add(m[1].replace(/^[“”"]+/, ''), v);
  }
}
console.log('候选名（说话主语位）:', cand.size);

// 全文提及数 + 首末章 + 性别代词（对候选与已知种子都算，两遍扫描代价可接受）
const all = [...cand.keys()];
const stat = new Map();
for (const n of all) stat.set(n, { speaker: cand.get(n).speaker, verbKinds: cand.get(n).verbs.size, total: 0, first: 0, last: 0, she: 0, he: 0 });
let idx = 0;
for (const f of files) {
  idx++;
  const t = fs.readFileSync(path.join(CH_DIR, f), 'utf8');
  const sents = t.split(/[。！？\n]/);
  for (const n of all) {
    if (!t.includes(n)) continue;
    const c = (t.match(new RegExp(n, 'g')) || []).length;
    const s = stat.get(n);
    s.total += c;
    if (!s.first) s.first = idx;
    s.last = idx;
    for (const sen of sents) {
      if (!sen.includes(n)) continue;
      if (sen.includes('她')) s.she++;
      if (sen.includes('他')) s.he++;
    }
  }
}
// 输出：候选（高频在前）
const rows = all.map(n => ({ name: n, ...stat.get(n), gender: stat.get(n).she > stat.get(n).he * 1.5 && stat.get(n).she >= 5 ? '女' : (stat.get(n).he > stat.get(n).she * 1.5 && stat.get(n).he >= 5 ? '男' : '') }))
  .sort((a, b) => b.speaker - a.speaker);
const CAND_MIN = +(process.env.CAND_MIN || 6); // 说话位次数下限（可被环境变量覆盖）
const candidates = rows.filter(r => r.speaker >= CAND_MIN && (r.speaker >= 12 || r.verbKinds >= 3 || (r.verbKinds >= 2 && r.total >= 30)));
