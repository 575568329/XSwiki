import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(new URL(import.meta.url)));
const textStats = {}; // book -> Map(name -> {total, first, last, she, he})

function loadStats(book, chDir) {
  const files = fs.readdirSync(chDir).filter(f => f.endsWith('.txt')).sort((a, b) => parseInt(a) - parseInt(b));
  const map = new Map();
  textStats[book] = { list: files, count: files.length, map, chDir };
  return map;
}
function statFor(book, names) {
  // 对给定名字（含别名合并）重算统计
  const { list, map } = textStats[book];
  const stat = { total: 0, first: 0, last: 0, she: 0, he: 0, chapters: 0 };
  let idx = 0;
  for (const f of list) {
    idx++;
    const t = fs.readFileSync(path.join(textStats[book].chDir, f), 'utf8');
    let hit = 0;
    for (const n of names) hit += (t.match(new RegExp(n, 'g')) || []).length;
    if (!hit) continue;
    stat.total += hit;
    stat.chapters++;
    if (!stat.first) stat.first = idx;
    stat.last = idx;
    for (const sen of t.split(/[。！？\n]/)) {
      if (!names.some(n => sen.includes(n))) continue;
      if (sen.includes('她')) stat.she++;
      if (sen.includes('他')) stat.he++;
    }
  }
  for (const n of names) map.set(n, stat);
  return stat;
}
const chDirOf = book => path.join(ROOT, book, 'text', 'chapters');
