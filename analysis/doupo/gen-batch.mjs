const only = process.argv[2];
for (const [name, prompt] of JOBS) {
  if (only && !name.includes(only)) continue;
  const out = path.join(OUT, name);
  if (fs.existsSync(out + '_nowm.jpg')) { console.log('跳过（已有）:', name); continue; }
  let okFlag = false;
  for (let i = 1; i <= 3 && !okFlag; i++) {
    try {
      console.log(`[${name}] 生成中（第${i}次）…`);
      const r = execFileSync(process.execPath, [GEN, 't2i', '--prompt', prompt, '--out', out], { encoding: 'utf8', timeout: 200000 });
      console.log(r.trim().split('\n').slice(-2).join('\n'));
      okFlag = fs.existsSync(out + '_nowm.jpg');
    } catch (e) {
      console.log(`  失败: ${String(e.message).slice(0, 140)}`);
      await new Promise(r => setTimeout(r, 3000));
    }
  }
  console.log(okFlag ? `✓ ${name}` : `✗ ${name} 三次未出图`);
}
console.log('批次完成');
